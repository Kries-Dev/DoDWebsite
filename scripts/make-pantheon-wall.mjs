// Builds the "Choose your deity" wall assets from Kries's original 1920×1080 pantheon panels.
//   brand-source/pantheons/<pantheon>.png      originals
//   brand-source/pantheons/medallions.json     medallion centres in source pixels (4 per panel)
// Writes:
//   public/pantheons/<pantheon>.webp (+ -960.webp)  scene for the wall
//   public/pantheons/medals/<pantheon>-<n>.webp       each medallion cut out (ring + portrait), round, transparent
//   public/pantheons/filler-left.webp / filler-right.webp   dark jungle side panels for the Aztec row
//   src/data/pantheon-wall.json                        positions in % for the page
import fs from 'node:fs/promises';
import sharp from 'sharp';

const SRC = 'brand-source/pantheons';
const OUT = 'public/pantheons';
const W = 1920, H = 1080, R = 214; // outer medallion radius in source pixels
const centres = JSON.parse(await fs.readFile(`${SRC}/medallions.json`, 'utf8'));

const layout = [
  [
    { id: 'greek', pantheon: 'Greek', fx: ['ember'], slots: ['zeus', 'hades', 'poseidon', 'demeter'] },
    { id: 'egyptian', pantheon: 'Egyptian', fx: ['ember'], slots: ['ra', 'isis', 'set', 'discord'] },
    { id: 'norse', pantheon: 'Norse', fx: ['snow'], slots: ['odin', 'thor', 'loki', 'freyr'] },
  ],
  [
    { id: 'atlantean', pantheon: 'Atlantean', fx: ['mote'], slots: ['gaia', 'oranos', 'kronos', 'discord'] },
    { id: 'chinese', pantheon: 'Chinese', fx: ['ember'], slots: ['fuxi', 'nuwa', 'shennong', 'discord'] },
    { id: 'japanese', pantheon: 'Japanese', fx: ['rain', 'petal'], slots: ['amaterasu', 'tsukuyomi', 'susanoo', 'discord'] },
  ],
  [
    { id: 'filler-left', filler: true, slots: [] },
    { id: 'aztec', pantheon: 'Aztec', fx: ['ember'], slots: ['huitzilopochtli', 'tezcatlipoca', 'quetzalcoatl', 'discord'] },
    { id: 'filler-right', filler: true, slots: [] },
  ],
];

await fs.mkdir(`${OUT}/medals`, { recursive: true });
const circle = (size) => Buffer.from(
  `<svg width="${size}" height="${size}"><defs><radialGradient id="g"><stop offset="96%" stop-color="#fff"/><stop offset="100%" stop-color="#fff" stop-opacity="0"/></radialGradient></defs><circle cx="${size / 2}" cy="${size / 2}" r="${size / 2}" fill="url(#g)"/></svg>`,
);

const rows = [];
for (const row of layout) {
  const outRow = [];
  for (const p of row) {
    if (p.filler) { outRow.push({ id: p.id, image: `/pantheons/${p.id}.webp`, filler: true, slots: [] }); continue; }
    const src = `${SRC}/${p.id}.png`;
    await sharp(src).resize(1600).webp({ quality: 80 }).toFile(`${OUT}/${p.id}.webp`);
    await sharp(src).resize(960).webp({ quality: 76 }).toFile(`${OUT}/${p.id}-960.webp`);
    const slots = [];
    for (const [k, slot] of p.slots.entries()) {
      const [cx, cy] = centres[p.id][k];
      const left = Math.max(0, cx - R), top = Math.max(0, cy - R);
      const size = Math.min(2 * R, W - left, H - top);
      const file = `${p.id}-${k + 1}.webp`;
      const crop = await sharp(src).extract({ left, top, width: size, height: size }).resize(360, 360).png().toBuffer();
      await sharp(crop).composite([{ input: circle(360), blend: 'dest-in' }]).webp({ quality: 86, alphaQuality: 90 }).toFile(`${OUT}/medals/${file}`);
      slots.push({ slot, medal: `/pantheons/medals/${file}`, x: +(cx / W * 100).toFixed(2), y: +(cy / H * 100).toFixed(2), d: +(2 * R / W * 100).toFixed(2) });
    }
    outRow.push({ id: p.id, pantheon: p.pantheon, image: `/pantheons/${p.id}.webp`, imageSmall: `/pantheons/${p.id}-960.webp`, fx: p.fx, slots });
  }
  rows.push(outRow);
}

// Side panels for the Aztec row: the Aztec jungle canopy (no medallions), mirrored outward, blurred and darkened.
const canopy = (left) => sharp(`${SRC}/aztec.png`).extract({ left, top: 0, width: 760, height: 428 }).resize(1600, 900);
await canopy(0).flop().blur(5).modulate({ brightness: 0.36, saturation: 0.75 }).webp({ quality: 70 }).toFile(`${OUT}/filler-left.webp`);
await canopy(1160).flop().blur(5).modulate({ brightness: 0.36, saturation: 0.75 }).webp({ quality: 70 }).toFile(`${OUT}/filler-right.webp`);

await fs.writeFile('src/data/pantheon-wall.json', JSON.stringify({
  _note: 'Generated by scripts/make-pantheon-wall.mjs from brand-source/pantheons. Positions are % of the panel; d = medallion diameter as % of panel width.',
  rows,
}, null, 2) + '\n');
console.log('Wall built:', rows.flat().filter((p) => !p.filler).map((p) => `${p.id} (${p.slots.length})`).join(', '));
